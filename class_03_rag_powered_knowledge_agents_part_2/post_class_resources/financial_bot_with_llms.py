from langchain_core.tools import tool
from langchain.agents import create_agent
import yfinance as yf

@tool
def search_stock_news(company: str) -> str:
    """Search Yahoo Finance for recent company news."""
    try:
        articles = yf.Search(company, news_count=5).news

        if not articles:
            return f"No news found for {company}."

        results = []
        for article in articles:
            content = article.get("content", article)
            title = content.get("title", "Untitled")
            url = content.get("canonicalUrl", {}).get("url", "")
            results.append(f"{title}\n{url}")

        return "\n\n".join(results)

    except Exception as e:
        return f"News search failed: {e}"


agent = create_agent(
    model=llm,
    tools=[search_stock_news]
)

result = agent.invoke({
    "messages": [
        {"role": "user", "content": "Find recent news about Claritev"}
    ]
})

print(result["messages"][-1].content)

